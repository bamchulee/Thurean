// ============================================================
// คลังข้อความตอบกลับลูกค้าในแชท LINE (ข้อความธรรมดา ไม่ใช่การ์ด)
// แบบเดียวกันทุกข้อความ:  บรรทัดแรก = หัวเรื่อง + อีโมจิ
//                           ย่อหน้าถัดไป = รายละเอียด
//                           ท้ายสุด = ลูกค้าต้องทำอะไรต่อ
// แก้คำพูดที่นี่ที่เดียว ไม่ต้องไล่หาในโค้ด webhook
// ============================================================
import { shopInfo } from "../../data/shop";

const baht = (n: number) => `฿${(n || 0).toLocaleString()}`;
const lines = (...parts: (string | false | undefined | null)[]) => parts.filter((p) => p !== false && p !== undefined && p !== null).join("\n");

export const replies = {
  // ---------- ทั่วไป ----------
  systemError: () =>
    lines("😥 ขออภัยครับ ระบบขัดข้องชั่วคราว", "", `ลองส่งใหม่อีกครั้ง หรือโทร ${shopInfo.phone} ได้เลยครับ 🙏`),

  cancelled: () => lines("👌 ยกเลิกรายการแล้วครับ", "เลือกเมนูด้านล่างเพื่อทำรายการต่อได้เลย"),

  // ---------- ออเดอร์ ----------
  orderNotFound: (ref?: string, trackingUrl?: string) =>
    lines(
      `🔎 ไม่พบออเดอร์${ref ? ` ${ref}` : "นี้"} ในบัญชี LINE นี้ครับ`,
      trackingUrl && "",
      trackingUrl && `ถ้าสั่งผ่านหน้าเว็บ เช็กสถานะได้ที่\n${trackingUrl}`
    ),

  noOrdersYet: () =>
    lines(
      "📭 ยังไม่มีออเดอร์ในบัญชี LINE นี้ครับ",
      "",
      "🍈 กด \"สั่งซื้อทุเรียน\" ที่เมนูด้านล่างเพื่อเริ่มจอง",
      "หรือพิมพ์เลขออเดอร์ที่ได้จากหน้าเว็บ (เช่น OD000123)"
    ),

  waitingToWeigh: (orderId: string) =>
    lines(
      `⚖️ ออเดอร์ #${orderId} รอแอดมินชั่งน้ำหนักอยู่ครับ`,
      "ยังไม่ต้องโอนนะครับ",
      "",
      "ชั่งเสร็จจะส่งยอดจริงพร้อม QR มาในแชทนี้ 🍈"
    ),

  orderStatusHint: (orderId: string, hint: string) => lines(`📦 ออเดอร์ #${orderId}`, hint),

  sendSlipPrompt: (orderId: string, amount: number) =>
    lines(
      `📸 ส่งรูปสลิปของออเดอร์ #${orderId} มาในแชทนี้ได้เลยครับ`,
      "",
      `💰 ยอดที่ต้องโอน ${baht(amount)}`,
      "",
      "ระบบจะตรวจสลิปให้อัตโนมัติ แล้วแจ้งผลในแชทนี้ครับ"
    ),

  // ---------- จอง ----------
  outOfStock: () =>
    lines("😢 ขออภัยครับ สินค้านี้หมด หรือปิดรับจองชั่วคราว", "", "🍈 ลองดูพันธุ์อื่นในเมนู \"สั่งซื้อทุเรียน\" ได้เลยครับ"),

  bookingFailed: (error: string) => lines("❌ จองไม่สำเร็จครับ", error, "", "ลองใหม่อีกครั้ง หรือกด \"คุยกับแอดมิน\" ได้เลย"),

  bookingDuplicate: (orderId: string) => lines(`ℹ️ การจองนี้บันทึกไว้แล้วครับ (ออเดอร์ #${orderId})`, "ไม่ได้สร้างออเดอร์ซ้ำ ไม่ต้องกังวลครับ"),

  // ---------- สลิป ----------
  slipUnreadable: (reason: string) =>
    lines("📷 อ่านรูปสลิปไม่ได้ครับ", `(${reason})`, "", "รบกวนส่งใหม่เป็นรูป JPG หรือ PNG อีกครั้งนะครับ"),

  slipProblem: (p: { orderId: string; notes: string[]; expected: number; bank: { bank: string; number: string; name: string } }) =>
    lines(
      `⚠️ สลิปของออเดอร์ #${p.orderId} ยังไม่ตรงครับ`,
      ...p.notes.map((n) => `• ${n}`),
      "",
      `💰 ยอดที่ต้องโอน ${baht(p.expected)}`,
      `🏦 ${p.bank.bank} ${p.bank.number}`,
      `     ${p.bank.name}`,
      "",
      "แอดมินจะตรวจอีกครั้ง ถ้าโอนเพิ่มแล้ว ส่งสลิปใหม่มาได้เลยครับ"
    ),

  slipLinkedToLatest: (orderId: string, others: number) =>
    lines(
      `🧾 ผูกสลิปกับออเดอร์ล่าสุด #${orderId} แล้วครับ`,
      `(ยังมีอีก ${others} ออเดอร์ที่รอชำระ)`,
      "",
      "ถ้าผิดออเดอร์ กด \"คุยกับแอดมิน\" ได้เลยครับ"
    ),

  imageReceived: (bookedOrderId?: string) =>
    bookedOrderId
      ? lines(
          "🙏 ได้รับรูปแล้วครับ",
          "",
          `ออเดอร์ #${bookedOrderId} ยังรอแอดมินชั่งน้ำหนัก ยังไม่ต้องโอนนะครับ`,
          "ชั่งเสร็จจะส่งยอดจริงพร้อม QR ให้ในแชทนี้"
        )
      : lines("🙏 ได้รับรูปแล้วครับ", "แอดมินจะดูแล้วตอบกลับในแชทนี้ครับ"),

  // ---------- ได้รับของ ----------
  alreadyReceived: (orderId: string) => lines(`✅ ออเดอร์ #${orderId} บันทึกว่าได้รับของแล้วครับ`, "ขอบคุณที่อุดหนุนนะครับ 🙏"),

  notShippedYet: (orderId: string, status: string) =>
    lines(`📦 ออเดอร์ #${orderId} ยังไม่ได้ออกจัดส่งครับ`, `สถานะตอนนี้: ${status}`, "", "ของออกจากร้านแล้วจะแจ้งในแชทนี้ครับ"),

  saved: () => "✅ บันทึกแล้วครับ",

  // ---------- คุยกับแอดมิน / เคลม ----------
  ticketSent: (ticketId: string) =>
    lines(`✅ ส่งเรื่องถึงแอดมินแล้วครับ`, `เลขเรื่อง #${ticketId}`, "", "แอดมินจะตอบกลับในแชทนี้โดยเร็วครับ 🙏"),

  // ---------- สั่งแบบพิมพ์เอง ----------
  soldPerFruit: (productName: string, weight?: string) =>
    lines(
      `⚖️ ${productName} ขายเป็นลูก แล้วคิดเงินตามน้ำหนักจริงครับ`,
      weight ? `(ลูกละประมาณ ${weight})` : false,
      "",
      "เลือกจำนวนลูกด้านล่างได้เลยครับ 👇"
    ),

  whichProduct: (names: string[]) =>
    names.length
      ? lines("🤔 ตรงกับหลายรายการครับ", ...names.map((n) => `• ${n}`), "", "เลือกจากเมนูด้านล่างได้เลยครับ 👇")
      : lines("🍈 ยินดีครับ รอบนี้มีตามนี้", "", "เลือกจากเมนูด้านล่างได้เลยครับ 👇"),

  multiOrderForwarded: (items: string[]) =>
    lines(
      "📝 รับรายการแล้วครับ",
      ...items.map((i) => `• ${i}`),
      "",
      "แอดมินจะสรุปยอดและยืนยันในแชทนี้ครับ 🙏"
    ),

  questionForwarded: () => lines("💬 ส่งข้อความให้แอดมินแล้วครับ", "", "แอดมินจะตอบกลับในแชทนี้โดยเร็วครับ 🙏"),

  thanks: () => "ยินดีครับ 🙏 ถ้าต้องการอะไรเพิ่ม พิมพ์มาได้เลยครับ",

  claimFailed: (error: string) => lines("❌ ส่งเคลมไม่สำเร็จครับ", error, "", "ลองใหม่อีกครั้ง หรือกด \"คุยกับแอดมิน\" ได้เลย"),
};
